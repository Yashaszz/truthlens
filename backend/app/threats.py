"""Threat matrix and decisive verdicts.

Analyzers put calibrated per-threat probabilities into summary["scores"] (e.g. {"ai_generated": 0.93}).
This module turns them, plus findings and the investigator's claim, into:
  * a threat matrix per evidence item (every threat for that media type, with status + evidence), and
  * one decisive verdict per item and for the case: the most probable threat, or AUTHENTIC.
Uncertain results still state which way they lean; they never return "can't tell"."""
from __future__ import annotations

import re

THREATS = {
    "image": [
        ("ai_generated", "AI-generated image", "Created entirely by an image generator (Midjourney, DALL-E, Stable Diffusion, Gemini, Flux…)"),
        ("face_swap", "Face swapping", "A real face replaced with someone else's"),
        ("manipulation", "Image manipulation", "Edited or retouched after capture"),
        ("compositing", "Image compositing", "Parts of different pictures combined, or areas cloned"),
        ("hidden_ai", "Hidden AI alterations", "AI used to change only part of a real photo (inpainting, generative fill)"),
        ("impersonation", "Fake identity & impersonation", "A synthetic or altered face presented as a real person"),
        ("misinformation", "Misinformation & fake news", "Fake or altered media presented as a real event"),
        ("harassment", "Harassment & defamation", "Altered media of an identifiable person used to harm or shame them"),
        ("fake_evidence", "Fake digital evidence", "A doctored photo, screenshot or document passed off as proof"),
        ("metadata", "Metadata manipulation", "File information edited, stripped or inconsistent with the picture"),
    ],
    "video": [
        ("face_swap", "Face-swap deepfake", "A person's face replaced throughout the video"),
        ("lip_sync", "Lip-sync deepfake", "Mouth movements re-generated to match different words"),
        ("ai_generated", "AI-generated video", "Footage generated by a video model (Sora, Veo, Runway, Kling…)"),
        ("voice_clone", "Cloned or dubbed voice", "The soundtrack is a synthetic or replaced voice"),
        ("edited", "Spliced or edited footage", "Cuts, inserted or removed segments"),
        ("impersonation", "Impersonation", "A real, named person made to appear to say or do something"),
        ("misinformation", "Misinformation & fake news", "Fake media or false claims about what the video shows"),
        ("harassment", "Harassment & defamation", "Altered video of an identifiable person used to harm them"),
        ("recycled", "Recycled or out-of-context footage", "Old footage presented as new or from somewhere else"),
        ("metadata", "Metadata manipulation", "Re-encoded or edited file information"),
    ],
    "audio": [
        ("voice_clone", "Voice cloning / synthetic speech", "Speech generated by text-to-speech or voice-conversion"),
        ("spliced", "Spliced or edited recording", "Words or sentences cut and rearranged"),
        ("fabricated_quote", "Fabricated quote", "The claim attributes words that are not in the recording"),
        ("impersonation", "Impersonation", "A real, named person's voice imitated"),
        ("misinformation", "Misinformation & fake news", "Fake audio or false claims about what was said"),
        ("metadata", "Re-encoding & metadata", "Recording re-processed or band-limited after capture"),
    ],
}

PRIMARY = {  # threats that decide the verdict label
    "image": ["ai_generated", "face_swap", "hidden_ai", "compositing", "manipulation"],
    "video": ["face_swap", "lip_sync", "ai_generated", "voice_clone", "edited"],
    "audio": ["voice_clone", "spliced", "fabricated_quote"],
}
VERDICT_WORD = {
    "ai_generated": "AI-generated", "face_swap": "Deepfake: face swap", "hidden_ai": "AI-edited photo",
    "compositing": "Composited / doctored", "manipulation": "Edited / manipulated", "lip_sync": "Lip-sync deepfake",
    "voice_clone": "Cloned / synthetic voice", "edited": "Edited footage", "spliced": "Spliced recording",
    "fabricated_quote": "Fabricated quote",
}

HARM_WORDS = r"\b(nude|naked|sex|porn|drunk|high|arrest|arrested|affair|cheat|cheating|scandal|caught|bribe|bribery|racist|abuse|assault|criminal|corrupt|confess|confession|shame|slur)\w*"
EVIDENCE_WORDS = r"\b(receipt|screenshot|chat|whatsapp|message|proof|evidence|document|invoice|bank|transaction|payment|certificate|id card|passport|license|letter|record|report|court)\w*"
DISCLOSED_WORDS = r"\b(ai[- ]generated|ai art|generated with|made with ai|illustration|artwork|parody|satire|edited|photoshop(ped)?|concept art|render)\b"
NAME_HINT = r"\b([A-Z][a-z]+(?:\s+[A-Z][a-z]+)+)\b"


def derive_scores(kind: str, eid: str, signals: list, summary: dict) -> dict:
    """Per-threat probabilities for video/audio from the detector signals (images compute theirs in image.py)."""
    sig = {}
    for s in signals:
        if s["evidence_id"] == eid:
            sig.setdefault(s["detector"], s)

    def g(d):
        return sig[d]["score"] if d in sig else None

    def strong(d, thr):
        v = g(d)
        return v if (v is not None and v >= thr) else (0.2 if v is not None else None)

    voice = g("audio_spoof_model")
    a = (summary.get("audio") if kind == "video" else summary) or {}
    music = bool((a.get("music") or {}).get("is_music"))
    ds, nf = strong("digital_silence", 0.5), strong("noise_floor_jumps", 0.45)
    # noise-floor jumps are an unbenchmarked heuristic: alone they can only suggest editing (cap below 'likely')
    spliced = None if (ds is None and nf is None) else max(ds or 0, min(nf or 0, 0.45))
    if ds is not None and ds >= 0.5 and nf is not None and nf >= 0.45:
        spliced = max(spliced, 0.7)  # two independent splice cues
    audio_scores = {"voice_clone": None if music else voice, "spliced": None if music else spliced,
                    "metadata": g("audio_bandwidth"), "music": music}
    if kind == "audio":
        return audio_scores
    edits = [x for x in (strong("temporal_cuts", 0.45), strong("frozen_frames", 0.45)) if x is not None]
    return {"face_swap": g("face_deepfake_model"), "lip_sync": g("av_sync"), "ai_generated": g("ai_frames"),
            "edited": max(edits) if edits else None, "metadata": g("video_container"), "_audio": audio_scores}


def _status(p: float | None, applicable: bool = True, risk_only: bool = False) -> str:
    if not applicable:
        return "not_applicable"
    if p is None:
        return "not_checked"
    if risk_only:  # depends on how the media is presented, and no claim says so: report a risk, not a detection
        return "at_risk" if p >= 0.5 else "not_detected"
    return "detected" if p >= 0.7 else "likely" if p >= 0.5 else "not_detected"


def _fids(findings, eid, detectors):
    return [f["id"] for f in findings if f["evidence_id"] == eid and f["detector"] in detectors and f["score"] >= 0.5]


def _evidence(findings, eid, detectors, limit=3):
    return [f.get("plain") or f["title"] for f in findings if f["evidence_id"] == eid and f["detector"] in detectors
            and f["score"] >= 0.5][:limit]


def _claim_info(claim: str) -> dict:
    claim = claim or ""
    names = [n for n in re.findall(NAME_HINT, claim) if n.split()[0] not in ("The", "This", "A", "BREAKING", "Breaking")]
    return {
        "present": bool(claim.strip()),
        "names": names[:3],
        "harm": sorted(set(m.lower() for m in re.findall(HARM_WORDS, claim, re.I)))[:4],
        "evidence": sorted(set(m.lower() for m in re.findall(EVIDENCE_WORDS, claim, re.I)))[:4],
        "disclosed": bool(re.search(DISCLOSED_WORDS, claim, re.I)),
    }


def item_matrix(ev: dict, summary: dict, findings: list, signals: list, claim: dict) -> dict:
    kind = ev["modality"]
    if kind not in THREATS:
        return {}
    eid = ev["id"]
    sc = dict(summary.get("scores") or {})
    rows = {}

    def put(key, p, evidence=None, fids=None, applicable=True, note=None, risk_only=False):
        rows[key] = {"p": None if p is None else round(float(p), 3), "status": _status(p, applicable, risk_only),
                     "evidence": evidence or [], "finding_ids": fids or [], "note": note}

    text_sig = {s["detector"]: s for s in signals if s["evidence_id"] == eid and s["modality"] == "text"}
    quote_p = text_sig.get("quote_check", {}).get("score")
    date_p = text_sig.get("date_consistency", {}).get("score")
    context_p = max([x for x in (quote_p, date_p) if x is not None] or [None]) if (quote_p or date_p) else None

    if kind == "image":
        faces = len(summary.get("faces") or [])
        put("ai_generated", sc.get("ai_generated"), _evidence(findings, eid, {"generator_metadata", "ai_image_model", "ai_ensemble"}),
            _fids(findings, eid, {"generator_metadata", "ai_image_model", "ai_ensemble"}))
        put("face_swap", sc.get("face_swap") if faces else None, _evidence(findings, eid, {"face_deepfake_model", "face_ensemble"}),
            _fids(findings, eid, {"face_deepfake_model", "face_ensemble"}), applicable=faces > 0,
            note=None if faces else "No face in the picture")
        put("manipulation", sc.get("manipulation"), _evidence(findings, eid, {"ela", "jpeg_grid", "exif_software", "manip_model"}),
            _fids(findings, eid, {"ela", "jpeg_grid", "exif_software", "manip_model"}))
        put("compositing", sc.get("compositing"), _evidence(findings, eid, {"noise_residual", "copy_move", "ela"}),
            _fids(findings, eid, {"noise_residual", "copy_move"}))
        has_trufor = summary.get("trufor") is not None
        hp = sc.get("hidden_ai")
        put("hidden_ai", max(hp or 0, sc.get("compositing") or 0) if has_trufor else hp,
            _evidence(findings, eid, {"ai_tiles", "trufor"}), _fids(findings, eid, {"ai_tiles", "trufor"}),
            note=None if has_trufor or (hp or 0) >= 0.5 else
            "Low-sensitivity check without the TruFor forgery model: benchmarked to catch ~5% of AI inpainting (1% false alarms)")
        put("metadata", sc.get("metadata"), _evidence(findings, eid, {"metadata_deep", "exif_dates", "exif_software", "exif_missing"}),
            _fids(findings, eid, {"metadata_deep", "exif_dates", "exif_software"}))
        fake = max(sc.get("ai_generated") or 0, sc.get("face_swap") or 0 if faces else 0, sc.get("hidden_ai") or 0,
                   sc.get("compositing") or 0, sc.get("manipulation") or 0)
        synth_face = max(sc.get("face_swap") or 0, sc.get("ai_generated") or 0) if faces else None
    elif kind == "video":
        a = summary.get("audio") or {}
        asc = a.get("scores") or sc.get("_audio") or {}
        faces = summary.get("face_frames") or 0
        put("face_swap", sc.get("face_swap") if faces else None, _evidence(findings, eid, {"face_deepfake_model", "face_ensemble", "face_sharpness"}),
            _fids(findings, eid, {"face_deepfake_model", "face_ensemble", "face_sharpness"}), applicable=faces > 0,
            note=None if faces else "No clear face in the video")
        sync = summary.get("sync") or {}
        put("lip_sync", sc.get("lip_sync"), _evidence(findings, eid, {"av_sync"}), _fids(findings, eid, {"av_sync"}),
            applicable=bool(sync.get("assessable")), note=None if sync.get("assessable") else (sync.get("reason") or "Needs a visible speaking face"))
        put("ai_generated", sc.get("ai_generated"), _evidence(findings, eid, {"ai_frames"}), _fids(findings, eid, {"ai_frames"}))
        put("voice_clone", asc.get("voice_clone"), _evidence(findings, eid, {"audio_spoof_model", "voice_ensemble"}),
            _fids(findings, eid, {"audio_spoof_model", "voice_ensemble"}), applicable=bool(summary.get("has_audio")),
            note=None if summary.get("has_audio") else "No soundtrack")
        put("edited", max(sc.get("edited") or 0, asc.get("spliced") or 0) if (sc.get("edited") is not None or asc.get("spliced") is not None) else None,
            _evidence(findings, eid, {"temporal_cuts", "frozen_frames", "digital_silence", "noise_floor_jumps"}),
            _fids(findings, eid, {"temporal_cuts", "frozen_frames", "digital_silence", "noise_floor_jumps"}))
        put("metadata", sc.get("metadata"), _evidence(findings, eid, {"video_container"}), _fids(findings, eid, {"video_container"}))
        put("recycled", date_p if date_p is not None else None, _evidence(findings, eid, {"date_consistency"}),
            _fids(findings, eid, {"date_consistency"}), applicable=claim["present"], note=None if claim["present"] else "Needs the claim/caption to compare dates")
        fake = max(rows[k]["p"] or 0 for k in ("face_swap", "lip_sync", "ai_generated", "voice_clone", "edited") if rows[k]["status"] != "not_applicable")
        synth_face = max(sc.get("face_swap") or 0, rows["lip_sync"]["p"] or 0, asc.get("voice_clone") or 0) if (faces or summary.get("has_audio")) else None
    else:  # audio
        music = bool(sc.get("music"))
        put("voice_clone", sc.get("voice_clone"), _evidence(findings, eid, {"audio_spoof_model", "voice_ensemble", "pitch_smoothness", "audio_bandwidth"}),
            _fids(findings, eid, {"audio_spoof_model", "voice_ensemble"}), applicable=not music,
            note="Music recording: voice-clone detectors are trained on speech" if music else None)
        put("spliced", sc.get("spliced"), _evidence(findings, eid, {"digital_silence", "noise_floor_jumps"}),
            _fids(findings, eid, {"digital_silence", "noise_floor_jumps"}), applicable=not music,
            note="Music recording: splice heuristics assume speech with pauses" if music else None)
        put("fabricated_quote", quote_p, _evidence(findings, eid, {"quote_check"}), _fids(findings, eid, {"quote_check"}),
            applicable=quote_p is not None, note=None if quote_p is not None else "No quote in the claim to check")
        put("metadata", sc.get("metadata"), _evidence(findings, eid, {"audio_bandwidth"}), _fids(findings, eid, {"audio_bandwidth"}))
        fake = max(rows["voice_clone"]["p"] or 0, rows["spliced"]["p"] or 0)
        synth_face = rows["voice_clone"]["p"]

    # ---- context threats -------------------------------------------------------------------------
    person = (synth_face is not None)
    named = claim["names"]
    if person:
        p_imp = synth_face * (1.0 if named else 0.85)
        put("impersonation", p_imp, ([f"The claim names {', '.join(named)}."] if named else []) +
            ([f"{'Face' if kind != 'audio' else 'Voice'} shows synthetic or swapped traits ({synth_face:.0%})."] if synth_face >= 0.5 else []),
            note=None if named else "No named person in the claim: this is the risk if it is presented as a real person", risk_only=not named)
    else:
        put("impersonation", None, applicable=False, note="No person's face or voice to impersonate")

    if claim["present"]:
        presented_as_real = not claim["disclosed"]
        p_mis = max(fake if presented_as_real else fake * 0.3, context_p or 0)
        ev_mis = []
        if presented_as_real and fake >= 0.5:
            ev_mis.append("The media appears fake or altered, but the claim presents it as real.")
        if claim["disclosed"]:
            ev_mis.append("The claim itself discloses that the media is AI-made or edited.")
        if (quote_p or 0) >= 0.5:
            ev_mis.append("A quote in the claim is not in the recording.")
        if (date_p or 0) >= 0.5:
            ev_mis.append("Dates in the claim don't match the file.")
        put("misinformation", p_mis, ev_mis, _fids(findings, eid, {"quote_check", "date_consistency", "topic_overlap"}))
    else:
        put("misinformation", fake, ["If shared as a real event, this media would be misleading."] if fake >= 0.5 else [],
            note="No caption supplied: this is the risk if the media is shared as real", risk_only=True)

    if kind in ("image", "video"):
        if person:
            harm = claim["harm"]
            p_h = synth_face * (1.0 if harm else 0.55)
            put("harassment", p_h, ([f"The claim uses harmful framing ({', '.join(harm)})."] if harm else []) +
                (["An identifiable person is shown in altered media."] if synth_face >= 0.5 else []),
                note=None if harm else "No harmful framing in the claim: risk reflects altered media of a person", risk_only=not harm)
        else:
            put("harassment", None, applicable=False, note="No identifiable person")
    if kind == "image":
        looks_doc = (summary.get("format") == "PNG" and not summary.get("exif")) or bool(claim["evidence"])
        p_ev = max(sc.get("manipulation") or 0, sc.get("compositing") or 0, sc.get("hidden_ai") or 0, sc.get("ai_generated") or 0,
                   sc.get("metadata") or 0)
        put("fake_evidence", p_ev if looks_doc else p_ev * 0.6,
            ([f"The claim treats it as evidence ({', '.join(claim['evidence'])})."] if claim["evidence"] else []) +
            (["Screenshot-like file without camera data."] if summary.get("format") == "PNG" and not summary.get("exif") else []),
            note=None if claim["evidence"] else "Not presented as evidence in the claim: this is the risk if it were", risk_only=not claim["evidence"])

    matrix = [{"key": k, "name": n, "desc": d, **rows.get(k, {"p": None, "status": "not_checked", "evidence": [], "finding_ids": [], "note": None})}
              for k, n, d in THREATS[kind]]
    decide = _decisive(kind, rows, summary, findings, eid)
    v = verdict(kind, rows, decide)
    ens = (summary.get("ai_ensemble") or {}).get("parts") or {}
    if v.get("key") == "ai_generated" and len(ens) >= 2:
        hi = [m for m, p in ens.items() if p >= 0.8]
        lo = [m for m, p in ens.items() if p <= 0.1]
        if hi and lo:
            v["tier"] = "low"
            v["disagreement"] = (f"Detectors disagree: {', '.join(hi)} says AI-generated while {', '.join(lo)} says camera photo. "
                                 "Heavy retouching, beauty filters or 'AI enhance' processing can cause this, so check the details.")
    return {"kind": kind, "matrix": matrix, "verdict": v, "decisive": decide}


def _decisive(kind: str, rows: dict, summary: dict, findings: list, eid: str) -> dict:
    """Only calibrated, benchmarked detectors may decide the verdict (end-to-end benchmark: letting unmeasured
    heuristics decide produced 17.8% false alarms on real photos; calibrated-only: 1.0%). Heuristic rows stay in
    the matrix as supporting evidence."""
    def p(k):
        r = rows.get(k) or {}
        return r.get("p") if r.get("status") not in ("not_applicable", None) else None
    d = {}
    if kind == "image":
        d["ai_generated"] = p("ai_generated")
        d["face_swap"] = p("face_swap")
        if summary.get("trufor") is not None:  # learned forgery detector, opt-in
            d["compositing"] = summary["trufor"]["score"]
            d["hidden_ai"] = p("hidden_ai")
        strong_md = max([f["score"] for f in findings if f["evidence_id"] == eid and f["detector"] == "metadata_deep"
                         and f["category"] == "metadata" and f["score"] >= 0.7] or [0])
        if strong_md:
            d["manipulation"] = strong_md  # e.g. EXIF thumbnail that no longer matches the picture
    elif kind == "video":
        d["face_swap"] = p("face_swap")
        d["voice_clone"] = p("voice_clone")
        d["ai_generated"] = p("ai_generated")
        if (p("lip_sync") or 0) >= 0.5 and max(p("face_swap") or 0, p("voice_clone") or 0) >= 0.5:
            d["lip_sync"] = p("lip_sync")  # lip-sync heuristic decides only when a calibrated channel agrees
    else:
        d["voice_clone"] = p("voice_clone")
        if (p("spliced") or 0) >= 0.7:  # two independent splice cues
            d["spliced"] = p("spliced")
        d["fabricated_quote"] = p("fabricated_quote")
    return {k: v for k, v in d.items() if v is not None}


def verdict(kind: str, rows: dict, decide: dict | None = None) -> dict:
    if decide is not None:
        cands = [(k, v) for k, v in decide.items() if k in VERDICT_WORD]
    else:
        cands = [(k, rows[k]["p"]) for k in PRIMARY[kind] if k in rows and rows[k]["p"] is not None and rows[k]["status"] != "not_applicable"]
    if not cands:
        if kind == "audio" and rows.get("voice_clone", {}).get("status") == "not_applicable":
            return {"label": "Music: no speech to check", "key": "music", "confidence": None, "lean": None, "tier": "unknown", "fake": False}
        return {"label": "Not enough to judge", "key": None, "confidence": None, "lean": None, "tier": "unknown"}
    k, p = max(cands, key=lambda x: x[1])
    if p >= 0.6:
        tier = "high" if p >= 0.8 else "medium"
        return {"label": VERDICT_WORD[k], "key": k, "confidence": round(p, 3), "tier": tier, "lean": None, "fake": True}
    if p <= 0.4:
        conf = 1 - p
        return {"label": "Authentic", "key": "authentic", "confidence": round(conf, 3), "tier": "high" if conf >= 0.8 else "medium",
                "lean": None, "fake": False}
    lean_fake = p >= 0.5
    return {"label": f"Leaning {VERDICT_WORD[k].lower()}" if lean_fake else "Leaning authentic", "key": k if lean_fake else "authentic",
            "confidence": round(p if lean_fake else 1 - p, 3), "tier": "low", "lean": k, "fake": lean_fake}


def case_threats(case: dict, summaries: dict, findings: list, signals: list) -> dict:
    claim = _claim_info(case.get("context", ""))
    items = {}
    for ev in case["evidence"]:
        m = item_matrix(ev, summaries.get(ev["id"], {}), findings, signals, claim)
        if m:
            items[ev["id"]] = m
    if not items:
        return {"claim": claim, "items": {}, "verdict": {"label": "Not enough to judge", "tier": "unknown", "confidence": None}}
    fakes = [(eid, it["verdict"]) for eid, it in items.items() if it["verdict"].get("fake")]
    if fakes:
        eid, v = max(fakes, key=lambda x: x[1]["confidence"] or 0)
    else:
        eid, v = min(((eid, it["verdict"]) for eid, it in items.items() if it["verdict"].get("confidence") is not None),
                     key=lambda x: x[1]["confidence"], default=(None, {"label": "Not enough to judge", "tier": "unknown", "confidence": None}))
    return {"claim": claim, "items": items, "verdict": {**v, "evidence_id": eid}}
